"""Bit-exactness oracle for the seeded simulators.

Freezes the exact public outputs of the library — the float bits of
``BankRoll.history`` — for every simulator x strategy x scenario x seed x
trial-count combination, plus the legacy (process-global RNG) paths of the two
random simulators.

Any change that alters a single settlement bit fails this module, which makes
it the acceptance oracle for output-identical performance work: optimizations
must keep every frozen digest unchanged.

Regenerate on purpose only (then format)::

    uv run python tests/test_bit_exactness.py
    ruff format tests/test_bit_exactness.py

which rewrites the GOLDEN block between the markers below from the current
code.
"""

import hashlib
import random
from pathlib import Path

import numpy as np
import pytest

from keeks.bankroll import BankRoll
from keeks.binary_strategies import (
    CPPIStrategy,
    DrawdownAdjustedKelly,
    DynamicBankrollManagement,
    FixedFractionStrategy,
    FractionalKellyCriterion,
    KellyCriterion,
    MertonShare,
    NaiveStrategy,
    OptimalF,
)
from keeks.simulators import (
    RandomBinarySimulator,
    RandomUncertainBinarySimulator,
    RepeatedBinarySimulator,
)

INITIAL_FUNDS = 1000.0

# Scenario axes: standard dynamics, a fee-dominated flat fee large enough that
# a winning settlement can net negative (and a tight drawdown limit so the
# RuinError graceful stop triggers), and a sub-min_probability edge where most
# strategies decline to bet. Strategies must be built with the same payoff and
# loss as the simulator (see _validate_strategy_odds).
SCENARIOS = {
    "standard": {
        "payoff": 2.0,
        "loss": 1.0,
        "cost": 0.01,
        "fee": 0.01,
        "probability": 0.55,
        "max_draw_down": None,
    },
    "fee-heavy": {
        "payoff": 1.2,
        "loss": 0.7,
        "cost": 0.02,
        "fee": 0.5,
        "probability": 0.45,
        "max_draw_down": 0.05,
    },
    "subgate": {
        "payoff": 10.0,
        "loss": 1.0,
        "cost": 0.0,
        "fee": 0.0,
        "probability": 0.3,
        "max_draw_down": None,
    },
}

# Mirrors the benchmark factories: stateful strategies (CPPI, Dynamic) must be
# rebuilt per run because they carry state across evaluate() calls.
STRATEGY_FACTORIES = {
    "Kelly": lambda s: KellyCriterion(
        payoff=s["payoff"], loss=s["loss"], transaction_cost=s["cost"]
    ),
    "Half Kelly": lambda s: FractionalKellyCriterion(
        payoff=s["payoff"], loss=s["loss"], transaction_cost=s["cost"], fraction=0.5
    ),
    "Drawdown-adjusted Kelly": lambda s: DrawdownAdjustedKelly(
        payoff=s["payoff"],
        loss=s["loss"],
        transaction_cost=s["cost"],
        max_acceptable_drawdown=0.2,
    ),
    "Optimal f": lambda s: OptimalF(
        payoff=s["payoff"],
        loss=s["loss"],
        transaction_cost=s["cost"],
        win_rate=s["probability"],
        max_risk_fraction=0.2,
    ),
    "Naive": lambda s: NaiveStrategy(
        payoff=s["payoff"], loss=s["loss"], transaction_cost=s["cost"]
    ),
    "Fixed fraction 2%": lambda s: FixedFractionStrategy(
        fraction=0.02, payoff=s["payoff"], loss=s["loss"], transaction_cost=s["cost"]
    ),
    "CPPI": lambda s: CPPIStrategy(
        floor_fraction=0.8,
        multiplier=2.0,
        initial_bankroll=INITIAL_FUNDS,
        payoff=s["payoff"],
        loss=s["loss"],
        transaction_cost=s["cost"],
    ),
    "Dynamic": lambda s: DynamicBankrollManagement(
        base_fraction=0.05,
        payoff=s["payoff"],
        loss=s["loss"],
        transaction_cost=s["cost"],
    ),
    "Merton share": lambda s: MertonShare(
        payoff=s["payoff"],
        loss=s["loss"],
        transaction_cost=s["cost"],
        risk_aversion=2.0,
    ),
}

SIMULATOR_NAMES = ("repeated", "random", "random-uncertain")

# Grid of seeds and trial counts. Short runs catch early stops and the no-bet
# path; the 400-trial runs compound. Legacy cases pin the process-global RNG
# branch (seed=None) that the seeded branch must not disturb.
SEEDS = (0, 1, 42, 20260803)
TRIAL_COUNTS = (7, 53, 400)
LEGACY_SEEDS = (7, 99)
LEGACY_TRIALS = (25, 120)
LEGACY_SIMULATOR_NAMES = ("random", "random-uncertain")


def run_case(simulator_name, strategy_name, scenario_name, seed, trials, legacy):
    """Run one grid cell and return the full bankroll history."""
    scenario = SCENARIOS[scenario_name]
    strategy = STRATEGY_FACTORIES[strategy_name](scenario)
    bankroll = BankRoll(
        initial_funds=INITIAL_FUNDS, max_draw_down=scenario["max_draw_down"]
    )
    sim_seed = None if legacy else seed
    if legacy:
        random.seed(seed)
        np.random.seed(seed)

    if simulator_name == "repeated":
        simulator = RepeatedBinarySimulator(
            payoff=scenario["payoff"],
            loss=scenario["loss"],
            transaction_costs=scenario["fee"],
            probability=scenario["probability"],
            trials=trials,
            seed=sim_seed,
        )
    elif simulator_name == "random":
        simulator = RandomBinarySimulator(
            payoff=scenario["payoff"],
            loss=scenario["loss"],
            transaction_costs=scenario["fee"],
            trials=trials,
            seed=sim_seed,
        )
    elif simulator_name == "random-uncertain":
        simulator = RandomUncertainBinarySimulator(
            payoff=scenario["payoff"],
            loss=scenario["loss"],
            transaction_costs=scenario["fee"],
            trials=trials,
            seed=sim_seed,
        )
    else:  # pragma: no cover - guarded by the frozen keys
        raise ValueError(f"Unknown simulator {simulator_name!r}")

    simulator.evaluate_strategy(strategy, bankroll)
    return bankroll.history


def _digest(history):
    """SHA-256 over the hex repr of every history float (exact bits)."""
    joined = " ".join(value.hex() for value in history)
    return hashlib.sha256(joined.encode("ascii")).hexdigest()


def generate_golden():
    """Digest every cell of the grid against the current code."""
    golden = {}
    for simulator_name in SIMULATOR_NAMES:
        for strategy_name in STRATEGY_FACTORIES:
            for scenario_name in SCENARIOS:
                for seed in SEEDS:
                    for trials in TRIAL_COUNTS:
                        key = (
                            simulator_name,
                            strategy_name,
                            scenario_name,
                            seed,
                            trials,
                            False,
                        )
                        golden[key] = _digest(run_case(*key))
    for simulator_name in LEGACY_SIMULATOR_NAMES:
        for strategy_name in STRATEGY_FACTORIES:
            for scenario_name in SCENARIOS:
                for seed in LEGACY_SEEDS:
                    for trials in LEGACY_TRIALS:
                        key = (
                            simulator_name,
                            strategy_name,
                            scenario_name,
                            seed,
                            trials,
                            True,
                        )
                        golden[key] = _digest(run_case(*key))
    return golden


